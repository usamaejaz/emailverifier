import { readFile, writeFile } from 'node:fs/promises'

const sourceUrl = 'https://raw.githubusercontent.com/disposable/disposable-email-domains/master/domains_mx.txt'
const outputUrl = new URL('../src/data/disposable-domains.generated.ts', import.meta.url)
const domainPattern = /^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/

const response = await fetch(sourceUrl)
if (!response.ok) throw new Error(`Disposable-domain download failed with HTTP ${response.status}.`)

const domains = [...new Set((await response.text())
  .split(/\r?\n/)
  .map(domain => domain.trim().toLowerCase())
  .filter(domain => domainPattern.test(domain)))].sort()

if (domains.length < 10_000) {
  throw new Error(`Disposable-domain update returned only ${domains.length} valid domains.`)
}

const previous = await readFile(outputUrl, 'utf8').catch(() => '')
const previousList = previous.match(/`([\s\S]*?)`\.split\('\\n'\)/)?.[1]?.split('\n') ?? []
if (previousList.length > 0) {
  const changeRatio = domains.length / previousList.length
  if (changeRatio < 0.9 || changeRatio > 1.5) {
    throw new Error(`Disposable-domain count changed unexpectedly from ${previousList.length} to ${domains.length}.`)
  }

  if (domains.length === previousList.length && domains.every((domain, index) => domain === previousList[index])) {
    console.log(`Disposable-domain snapshot is already current at ${domains.length} domains.`)
    process.exit(0)
  }
}

const updatedAt = new Date().toISOString()
const output = `// Generated by npm run update:data from ${sourceUrl}
// Vendored under the MIT license documented in THIRD_PARTY_NOTICES.md.
export const disposableDataUpdatedAt = '${updatedAt}'
export const upstreamDisposableDomainList = \`${domains.join('\n')}\`.split('\\n')
`

await writeFile(outputUrl, output, 'utf8')
console.log(`Vendored ${domains.length} disposable domains.`)
